#!/usr/bin/env python3
"""Build core/ : verbatim extracts of the career-ops files every Track B run would otherwise load whole.

career-ops/AGENTS.md (~100 KB) and its router SKILL.md (~27 KB) are written for many CLIs and installs.
Most of that text never applies to this skill. This script splits them by heading into:
  core     always read        -> copied verbatim into core/*.md
  ondemand read only when...   -> listed in core/*.md as exact line ranges of the upstream file
  drop     never applies here  -> listed by name only
A heading this script doesn't know goes to core (safe default) and is reported, so an upstream sync
can never silently hide a new rule.

  python3 tools/build_core.py          write core/
  python3 tools/build_core.py --check  exit 1 if core/ is stale (used by `jh.py verify`)
"""
import re, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
CO = SKILL / "career-ops"
OUT = SKILL / "core"

AGENTS_RULES = {
    "drop": {
        "# career-ops: open-source AI job search agent": "title",
        "## Origin": "project history",
        "## Update Check": "replaced: update with scripts/sync-career-ops.sh (SKILL.md)",
        "## What is career-ops": "intro",
        "### Codex invocation": "other CLI",
        "### Pi invocation": "other CLI",
        "### Oh My Pi (omp) invocation": "other CLI",
        "## CI/CD, Community and Governance": "repo maintenance",
        "## Community asks (one at a time, once each)": "star/manifesto prompts, off in this skill",
    },
    "ondemand": {
        "### Main Files": "you need to know which script or file does something",
        "### Plugins (optional)": "the user asks about career-ops plugins",
        "### First Run — Onboarding (IMPORTANT)": "cv.md, config/profile.yml or modes/_profile.md is missing in DATA_ROOT",
        "### Language Modes": "`language.modes_dir` is set or the user targets a non-English market",
        "### Output Language vs Market Modes": "`language.modes_dir` is set or the user targets a non-English market",
        "## Headless / Batch Mode": "running `batch`, a subagent worker, or 2+ evaluations at once (report-number reservation)",
        "### Celebrating a hire (the Hired Wall)": "an application's outcome is Hired",
    },
}

ROUTER_RULES = {
    "drop": {
        "__preamble__": "frontmatter",
        "# career-ops: open-source AI job search agent": "title",
        "## Project Root Resolution": "fixed by SKILL.md: PROJECT_ROOT = career-ops/",
        "### Skill installed without career-ops": "career-ops is vendored, never install it",
        "### Claude Code plugin install": "not a plugin install",
        "## Invocation Notes": "other CLIs",
        "## Session Title (host-optional, #5303)": "Claude Code gives the agent no rename tool: skip silently",
    },
    "ondemand": {
        "## Discovery Mode (no arguments)": "the user asks for the career-ops menu or command list",
    },
}


def sections(path):
    lines = path.read_text().splitlines(keepends=True)
    out, cur = [], {"title": "__preamble__", "start": 1, "lines": []}
    fence = False
    for i, line in enumerate(lines, 1):
        if line.lstrip().startswith("```"):
            fence = not fence
        if not fence and re.match(r"^#{1,3} \S", line):
            if cur["lines"] or cur["title"] != "__preamble__":
                out.append(cur)
            cur = {"title": line.rstrip("\n"), "start": i, "lines": []}
        cur["lines"].append(line)
    out.append(cur)
    for s in out:
        s["end"] = s["start"] + len(s["lines"]) - 1
        s["text"] = "".join(s["lines"])
    return out


def classify(secs, rules, src_name):
    known = set(rules["drop"]) | set(rules["ondemand"])
    seen = {s["title"] for s in secs}
    warnings = [f"{src_name}: rule for missing heading {h!r} (renamed upstream?)" for h in known
                if h not in seen and h != "__preamble__"]
    core, ond, drop = [], [], []
    for s in secs:
        t = s["title"]
        if t in rules["drop"]:
            drop.append((s, rules["drop"][t]))
        elif t in rules["ondemand"]:
            ond.append((s, rules["ondemand"][t]))
        else:
            if t == "__preamble__" and not s["text"].strip():
                continue
            core.append(s)
    return core, ond, drop, warnings


def render(name, src, secs, rules, version):
    core, ond, drop, warns = classify(secs, rules, src.name)
    rel = src.relative_to(SKILL)
    head = [
        f"<!-- GENERATED by tools/build_core.py from {rel} (career-ops {version}). Do not edit: run `python3 jh.py build`. -->\n",
        f"# {name}\n\n",
        f"Verbatim sections of `{rel}` that apply to every Track B run here. "
        f"Read this file instead of the whole source.\n\n",
    ]
    if ond:
        head.append(f"**Read on demand** (Read `{rel}` with offset/limit):\n\n| When | Section | offset | limit |\n|---|---|---|---|\n")
        for s, when in ond:
            head.append(f"| {when} | {s['title'].lstrip('# ')} | {s['start']} | {s['end'] - s['start'] + 1} |\n")
        head.append("\n")
    if drop:
        head.append("**Left out** (never applies in this skill): "
                    + "; ".join(f"{s['title'].lstrip('# ') if s['title'] != '__preamble__' else 'frontmatter'} ({why})"
                                for s, why in drop) + ".\n\n")
    head.append("---\n\n")
    body = "".join(s["text"] if s["text"].endswith("\n") else s["text"] + "\n" for s in core)
    return "".join(head) + body, warns, sum(len(s["text"].encode()) for s in core)


def build():
    version = (CO / "VERSION").read_text().split()[0] if (CO / "VERSION").exists() else "?"
    jobs = [
        ("career-ops rules (core of AGENTS.md)", CO / "AGENTS.md", AGENTS_RULES, OUT / "career-ops-rules.md"),
        ("career-ops router (core of its SKILL.md)", CO / ".agents/skills/career-ops/SKILL.md", ROUTER_RULES,
         OUT / "career-ops-router.md"),
    ]
    results, warns = [], []
    for name, src, rules, dest in jobs:
        text, w, _ = render(name, src, sections(src), rules, version)
        results.append((dest, text, src))
        warns += w
    return results, warns


def main():
    check = "--check" in sys.argv
    results, warns = build()
    stale = []
    for dest, text, src in results:
        if check:
            if not dest.exists() or dest.read_text() != text:
                stale.append(dest.name)
        else:
            dest.parent.mkdir(exist_ok=True)
            dest.write_text(text)
            print(f"wrote {dest.relative_to(SKILL)}  {len(text.encode()):>7,} B  (source {src.stat().st_size:>7,} B)")
    for w in warns:
        print(f"WARN {w}")
    if check:
        if stale:
            print(f"STALE core/: {', '.join(stale)}  -> run `python3 jh.py build`")
            return 1
        print("core/ fresh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
